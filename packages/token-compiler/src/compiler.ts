import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { buildTokenDictionary } from './resolver.js';
import { generateStylexVars, generateStylexTokensBarrel } from './generators/stylex.js';
import {
  generateBaseCss,
  generateDarkSchemeCss,
  generateHighContrastSchemeCss,
  generateDensityCss,
} from './generators/css.js';
import { generateTokenMetadata, generateTokenMarkdownTable } from './generators/docs.js';
import type { CompilerOptions } from './types.js';

export async function compileTokens(options: CompilerOptions = {}): Promise<void> {
  const rootDir = process.cwd();
  const stylexOutDir = options.stylexOutDir ?? path.resolve(rootDir, 'packages/stylex/src');
  const themesOutDir = options.themesOutDir ?? path.resolve(rootDir, 'packages/themes/src/css');
  const docsOutDir = options.docsOutDir ?? path.resolve(rootDir, 'docs/tokens');

  const dict = buildTokenDictionary();

  // 1. Generate StyleX Contracts
  await fs.mkdir(stylexOutDir, { recursive: true });
  await fs.writeFile(path.join(stylexOutDir, 'vars.stylex.ts'), generateStylexVars(dict), 'utf-8');
  await fs.writeFile(path.join(stylexOutDir, 'tokens.ts'), generateStylexTokensBarrel(), 'utf-8');
  await fs.writeFile(
    path.join(stylexOutDir, 'index.ts'),
    "export * from './vars.stylex.js';\nexport * from './tokens.js';\n",
    'utf-8',
  );

  // 2. Generate CSS Custom Properties Stylesheets
  await fs.mkdir(themesOutDir, { recursive: true });
  await fs.writeFile(path.join(themesOutDir, 'base.css'), generateBaseCss(dict), 'utf-8');
  await fs.writeFile(
    path.join(themesOutDir, 'theme-dark.css'),
    generateDarkSchemeCss(dict),
    'utf-8',
  );
  await fs.writeFile(
    path.join(themesOutDir, 'theme-high-contrast.css'),
    generateHighContrastSchemeCss(dict),
    'utf-8',
  );
  await fs.writeFile(path.join(themesOutDir, 'density.css'), generateDensityCss(dict), 'utf-8');

  // Index CSS importing all sheets
  const indexCss = [
    '/**',
    ' * @file Automatically generated by @pine-ui/token-compiler.',
    ' * DO NOT EDIT MANUALLY.',
    ' */',
    "@import './base.css';",
    "@import './theme-dark.css';",
    "@import './theme-high-contrast.css';",
    "@import './density.css';",
    '',
  ].join('\n');
  await fs.writeFile(path.join(themesOutDir, 'index.css'), indexCss, 'utf-8');

  // 3. Generate Documentation & Metadata
  await fs.mkdir(docsOutDir, { recursive: true });
  await fs.writeFile(
    path.join(docsOutDir, 'metadata.json'),
    JSON.stringify(generateTokenMetadata(dict), null, 2),
    'utf-8',
  );
  await fs.writeFile(path.join(docsOutDir, 'TOKENS.md'), generateTokenMarkdownTable(dict), 'utf-8');
}
